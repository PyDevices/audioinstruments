"""Write the ``audioinstruments`` face of every vrack instrument from its class.

    python tools/make_faces.py           # write lib/audioinstruments/
    python tools/make_faces.py --check   # exit 1 if any face is out of date

Each instrument ``vrack.adapter.create(voice=name)`` plays gets a module
``audioinstruments/<name>.py`` holding its metadata at module level, written
out as literals (a host such as a plug-in scanner reads the file as text, and
a frozen build reads it without importing vrack), and a ``create()`` that
builds it. The class is the source: change ``MACRO_MODES``, ``PATCHES`` or
``DISPLAY_NAME`` there and run this again. ``_names.py`` lists them.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "lib"))

from vrack import adapter  # noqa: E402

FACES = os.path.join(ROOT, "lib", "audioinstruments")
HEADER = (
    "# SPDX-FileCopyrightText: 2026 Brad Barnett\n"
    "# SPDX-License-Identifier: MIT\n"
    "# Generated by tools/make_faces.py from %s: edit that, then run it again.\n"
)


def version():
    with open(os.path.join(ROOT, "pyproject.toml")) as f:
        for line in f:
            if line.startswith("version"):
                return line.split("=", 1)[1].strip().strip('"')
    raise SystemExit("pyproject.toml has no version")


def text(s):
    return json.dumps(s, ensure_ascii=False)


def strings(items):
    if not items:
        return "()"
    return "(\n%s)" % "".join("    %s,\n" % text(s) for s in items)


def inline(items):
    """A short tuple of strings on one line, as ruff formats it."""
    body = ", ".join(text(s) for s in items)
    return "(%s,)" % body if len(items) == 1 else "(%s)" % body


def summary(module):
    """The first sentence of a module's docstring."""
    doc = (sys.modules[module].__doc__ or "").strip()
    first = " ".join(doc.split("\n\n")[0].split())
    return first.split(". ")[0].rstrip(".") + "."


def source(name):
    """(metadata holder, where it comes from, the module whose doc describes it)."""
    if name in adapter.SAMPLERS:
        module = "vrack." + name
        __import__(module)
        return sys.modules[module], module, module
    patch = (
        adapter.voice_patch(name) if name in adapter._PATCH_VOICES else adapter.ModuleVoice(name)
    )
    cls = patch._cls if isinstance(patch, adapter.ModuleVoice) else type(patch)
    return patch, "%s.%s" % (cls.__module__, cls.__name__), cls.__module__


def face(name):
    meta, origin, doc = source(name)
    display = getattr(meta, "DISPLAY_NAME", None) or meta.NAME
    labels = tuple(meta.MACRO_LABELS)
    modes = dict(meta.MACRO_MODES)
    out = [HEADER % origin, '"""%s"""\n\n' % summary(doc)]
    out.append("NAME = %s\n" % text(meta.NAME))
    out.append("DISPLAY_NAME = %s\n" % text(display))
    out.append("CATEGORIES = %s\n" % inline(getattr(meta, "CATEGORIES", ("Synth",))))
    out.append("VERSION = %s\n" % text(version()))
    out.append("VENDOR = %s\n\n" % text(getattr(meta, "VENDOR", "PyDevices")))
    out.append("MACRO_LABELS = %s\n\n" % strings(labels))
    out.append(
        "MACRO_MODES = {\n%s}\n\n"
        % "".join("    %d: %s,\n" % (i, text(modes[i])) for i in sorted(modes))
    )
    out.append(
        "PATCHES = {\n%s}\n"
        % "".join(
            "    %d: (%s, %s),\n" % (i, text(p[0]), tuple(int(v) for v in p[1]))
            for i, p in sorted(meta.PATCHES.items())
        )
    )
    for field in ("NOTE_MAP", "PAD_MAP"):
        value = getattr(meta, field, None)
        if value:
            out.append(
                "\n%s = (\n%s)\n"
                % (field, "".join("    (%d, %s),\n" % (k, text(v)) for k, v in value))
            )
    out.append(
        "\n\ndef create(sample_rate, channel_count=2, transport=None, **options):\n"
        '    """A live %s. See ``audioinstruments.create`` for the options."""\n'
        "    from . import _build\n\n"
        "    return _build(NAME, sample_rate, channel_count, transport, options)\n" % display
    )
    return "".join(out)


def names_module(faces, metas):
    instruments = [n for n in faces if n not in adapter.SAMPLERS]
    drums = [n for n in instruments if getattr(metas[n], "NOTE_MAP", None)]
    melodic = [n for n in instruments if n not in drums]
    return "".join(
        [
            HEADER % "vrack.adapter",
            '"""Which instruments the package has, written out so nothing lists a directory."""\n\n',
            "#: Every instrument.\nALL = %s\n\n" % strings(instruments),
            "#: The ones with a ``NOTE_MAP``: a drum machine.\nDRUM_MACHINES = %s\n\n"
            % strings(drums),
            "#: The rest.\nMELODIC = %s\n\n" % strings(melodic),
            "#: Instruments that play a SoundFont you supply, and take its ``bank=``.\n"
            "SAMPLERS = %s\n" % strings([n for n in faces if n in adapter.SAMPLERS]),
        ]
    )


def wanted():
    names = list(adapter.ALL)
    files = {"%s.py" % n: face(n) for n in names}
    files["_names.py"] = names_module(names, {n: source(n)[0] for n in names})
    return files


def main(argv):
    check = "--check" in argv
    stale = []
    for filename, body in sorted(wanted().items()):
        path = os.path.join(FACES, filename)
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current == body:
            continue
        stale.append(filename)
        if not check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(body)
    if check and stale:
        print("out of date, run tools/make_faces.py: " + ", ".join(stale))
        return 1
    print(("%d faces out of date" if check else "%d faces written") % len(stale))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
